"""Fase 10: mineração contra repositórios git sintéticos — série, primeiro uso, recall."""

from __future__ import annotations

from jmod.config import load_study
from jmod.features.parser import ScopeRules
from jmod.mining.adoption import mine_feature, scan_head
from jmod.repo.git import Repo

STUDY = load_study()
RULES = ScopeRules.from_config(STUDY.paths)
RECORD = STUDY.feature("record")
VAR = STUDY.feature("var")
SWITCH = STUDY.feature("switch_expression")


def _mine(r, feature):
    return mine_feature(Repo(r.path), "main", feature, RULES)


def test_introducao_remocao_e_readicao(synthetic) -> None:
    """A série precisa registrar o vaivém completo — é dela que sai o abandonment."""
    r = synthetic()
    r.commit({"src/main/java/A.java": "class A {}"})
    r.commit({"src/main/java/A.java": "class A { record P(int x) {} }"})
    r.commit({"src/main/java/A.java": "class A {}"})
    r.commit({"src/main/java/A.java": "class A { record Q(int y) {} record R(int z) {} }"})

    m = _mine(r, RECORD)
    prod = [(p.occurrence_count, p.file_count) for p in m.series if p.scope == "production"]
    assert prod == [(1, 1), (0, 0), (2, 1)]


def test_primeiro_uso_carrega_evidencia_auditavel(synthetic) -> None:
    r = synthetic()
    r.commit({"src/main/java/A.java": "class A {}"})
    sha = r.commit({"src/main/java/B.java": "class B {\n  record P(int x) {}\n}"})
    m = _mine(r, RECORD)
    assert len(m.first_uses) == 1
    fu = m.first_uses[0]
    assert (fu.sha, fu.path, fu.scope) == (sha, "src/main/java/B.java", "production")
    assert fu.hits[0].line == 2, "linha exata para auditoria manual"


def test_escopos_sao_series_independentes(synthetic) -> None:
    """Uso em teste antes de produção: duas séries, dois primeiros usos."""
    r = synthetic()
    r.commit({"src/test/java/T.java": "class T { record F(int a) {} }"})
    r.commit({"src/main/java/A.java": "class A { record P(int x) {} }"})
    m = _mine(r, RECORD)
    assert {f.scope for f in m.first_uses} == {"test", "production"}
    test_first = next(f for f in m.first_uses if f.scope == "test")
    prod_first = next(f for f in m.first_uses if f.scope == "production")
    assert test_first.committed_at < prod_first.committed_at


def test_codigo_gerado_nao_conta_como_producao(synthetic) -> None:
    r = synthetic()
    r.commit(
        {
            "src/main/java/G.java": (
                "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n"
                "class G { record P(int x) {} }"
            )
        }
    )
    m = _mine(r, RECORD)
    assert all(p.scope == "generated" for p in m.series)
    assert all(f.scope == "generated" for f in m.first_uses)


def test_falso_positivo_de_pickaxe_e_filtrado_pela_ast(synthetic) -> None:
    """`class record {}` entra como candidato (-S vê 'record ') e a AST descarta."""
    r = synthetic()
    r.commit({"src/main/java/A.java": 'class A { int record = 1; String s = "record x"; }'})
    m = _mine(r, RECORD)
    assert m.candidates, "o pickaxe deve ter gerado o candidato"
    assert m.series == [], "e a AST deve tê-lo descartado"
    assert m.first_uses == []


def test_conversao_de_switch_e_capturada_pelo_regex(synthetic) -> None:
    """A armadilha central: converter `case 1:` em `case 1 ->` preserva a contagem
    de 'switch' — só a estratégia -G da feature enxerga a modernização."""
    r = synthetic()
    antes = "class A { void m(int d){ switch(d){ case 1: f(); break; } } void f(){} }"
    depois = "class A { void m(int d){ switch(d){ case 1 -> f(); } } void f(){} }"
    r.commit({"src/main/java/A.java": antes})
    sha = r.commit({"src/main/java/A.java": depois})
    m = _mine(r, SWITCH)
    assert [f.sha for f in m.first_uses if f.scope == "production"] == [sha]


def test_renomeacao_preserva_contagem(synthetic) -> None:
    r = synthetic()
