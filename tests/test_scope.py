"""Classificação de escopo por caminho e cabeçalho."""

from __future__ import annotations

import pytest

from jmod.config import load_study
from jmod.features.parser import EXAMPLE, GENERATED, PRODUCTION, TEST, ScopeRules


@pytest.fixture(scope="module")
def rules() -> ScopeRules:
    return ScopeRules.from_config(load_study().paths)


@pytest.mark.parametrize(
    ("path", "esperado"),
    [
        ("src/main/java/com/acme/Service.java", PRODUCTION),
        ("core/src/main/java/A.java", PRODUCTION),
        ("src/test/java/com/acme/ServiceTest.java", TEST),
        ("module/src/test/java/A.java", TEST),
        ("tests/java/A.java", TEST),
        ("target/generated-sources/A.java", GENERATED),
        ("build/generated/A.java", GENERATED),
        ("third_party/lib/A.java", GENERATED),
        ("vendor/x/A.java", GENERATED),
        ("examples/Demo.java", EXAMPLE),
        ("samples/Demo.java", EXAMPLE),
        ("benchmarks/Bench.java", EXAMPLE),
    ],
)
def test_classifica_por_caminho(rules: ScopeRules, path: str, esperado: str) -> None:
    assert rules.classify(path) == esperado


def test_cabecalho_gerado_vence_caminho_de_producao(rules: ScopeRules) -> None:
    src = b"// Generated by the protocol buffer compiler. DO NOT EDIT!\npublic class A {}"
    assert rules.classify("src/main/java/A.java", src) == GENERATED


def test_gerado_vence_teste(rules: ScopeRules) -> None:
    """Arquivo gerado dentro de src/test continua sendo código que ninguém escreveu."""
    src = b'@Generated("jaxb")\npublic class A {}'
    assert rules.classify("src/test/java/A.java", src) == GENERATED


def test_producao_com_cabecalho_comum_permanece_producao(rules: ScopeRules) -> None:
    src = b"/*\n * Copyright 2020 Acme.\n * Licensed under Apache 2.0.\n */\npublic class A {}"
    assert rules.classify("src/main/java/A.java", src) == PRODUCTION


def test_marcador_gerado_tarde_demais_no_arquivo_e_ignorado(rules: ScopeRules) -> None:
    src = b"public class A {\n" + b"  // filler\n" * 80 + b"  // DO NOT EDIT\n}"
    assert rules.classify("src/main/java/A.java", src) == PRODUCTION
